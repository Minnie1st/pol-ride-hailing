    print("F2: Witness Request-Load Distribution")
    print("=" * 72)

    deployment_row = recommended_deployment["row"]
    deployment = strategy_orders[deployment_row["strategy"]][: deployment_row["witness_count"]]
    witness_index = WitnessSpatialIndex(deployment)
    params = deployment_params(args)

    load_rows = []
    heatmap_payload = {}
    panel_data = []

    labels = ["c10", "c50", "c100", "c200"]
    panel_labels = ["A", "B", "C", "D"]
    for label in labels:
        events = load_events(label)
        summary = load_summary(label)
        sim_duration_s = summary["results"]["sim_duration_s"]
        load_counts = Counter()

        for idx, event in enumerate(events):
            context = build_context(event, f"f2_{label}", idx)
            local_witnesses = witness_index.query(event["lat"], event["lon"], params.d_ble + 5.0)
            stable_seed(args.seed, "f2", label, idx)
            proof_result = generate_proof(
                prover_id=event["order_id"],
                actual_lat=event["lat"],
                actual_lon=event["lon"],
                claim_lat=event["lat"],
                claim_lon=event["lon"],
                timestamp=event["time"],
                ctx=context,
                witnesses=local_witnesses,
                params=params,
                candidate_mode="actual",
            )
            for check in proof_result.witness_checks:
                load_counts[check.witness_id] += 1

        hourly_loads = {
            witness.id: count / (sim_duration_s / 3600.0)
            for witness, count in ((witness, load_counts.get(witness.id, 0)) for witness in deployment)
        }
        nonzero = [value for value in hourly_loads.values() if value > 0]
        max_load = max(hourly_loads.values()) if hourly_loads else 0.0
        p95_load = percentile(nonzero, 95) if nonzero else 0.0
        mean_nonzero = statistics.mean(nonzero) if nonzero else 0.0
        hotspots = sorted(
            deployment,
            key=lambda witness: (-hourly_loads[witness.id], witness.id),
        )[:10]

