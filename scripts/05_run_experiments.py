def experiment_s2_replay(valid_proofs: Sequence[dict], args: argparse.Namespace) -> dict:
    print("\n" + "=" * 72)
    print("S2: Replay Resistance")
    print("=" * 72)

    params = deployment_params(args)
    trials = min(args.replay_trials, len(valid_proofs))
    rows = []

    def different_event_name(event_name: str) -> str:
        for candidate in EVENT_ORDER:
            if candidate != event_name:
                return candidate
        return f"{event_name}_other"

    scenario_defs = [
        ("exact_same_replay", "context_replay"),
        ("same_order_event_new_session", "event_accepted"),
        ("different_order_event_reuse", "context_binding"),
        ("stale_proof", "temporal"),
    ]

    for scenario_name, expected_mechanism in scenario_defs:
        reason_counts = Counter()
        rejected = 0
        for idx in range(trials):
            proof_record = valid_proofs[idx]
            proof = proof_record["proof"]
            event = proof_record["event"]
            original_ctx = proof_record["context"]

            if scenario_name == "exact_same_replay":
                c_used: set[str] = set()
                verify_proof(
                    proof,
                    event["lat"],
                    event["lon"],
                    event["time"] - 1.0,
                    event["time"] + 1.0,
                    params,
                    c_used,
                    expected_ctx=original_ctx,
                )
                second = verify_proof(
                    proof,
                    event["lat"],
                    event["lon"],
                    event["time"] - 1.0,
                    event["time"] + 1.0,
                    params,
                    c_used,
                    expected_ctx=original_ctx,
                )
            elif scenario_name == "same_order_event_new_session":
                accepted_events: set[str] = set()
                verify_proof(
                    proof,
                    event["lat"],
                    event["lon"],
                    event["time"] - 1.0,
                    event["time"] + 1.0,
                    params,
                    set(),
                    expected_ctx=original_ctx,
                    accepted_events=accepted_events,
                )
                second = verify_proof(
                    proof,
                    event["lat"],
                    event["lon"],
                    event["time"] - 1.0,
                    event["time"] + 1.0,
                    params,
                    set(),
                    expected_ctx={
                        **original_ctx,
                        "session_id": f"rebound_{idx}",
                    },
                    accepted_events=accepted_events,
                )
            elif scenario_name == "different_order_event_reuse":
                second = verify_proof(
                    proof,
                    event["lat"],
                    event["lon"],
                    event["time"] - 1.0,
                    event["time"] + 1.0,
                    params,
                    set(),
                    expected_ctx={
                        **original_ctx,
                        "order_id": f"other_order_{idx}",
                        "event": different_event_name(original_ctx["event"]),
                    },
                )
            else:
                second = verify_proof(
                    proof,
                    event["lat"],
                    event["lon"],
                    event["time"] + 600.0,
                    event["time"] + 900.0,
                    params,
                    set(),
                    expected_ctx=original_ctx,
                )

            accepted, reason = second
            if not accepted:
                rejected += 1
                reason_counts[reason] += 1

        row = {
            "scenario": scenario_name,
            "expected_mechanism": expected_mechanism,
            "trials": trials,
            "rejection_rate": rejected / trials if trials else 0.0,
            "observed_mechanisms": dict(reason_counts),
        }
        rows.append(row)
        print(
            f"  {scenario_name:24s}: reject={row['rejection_rate']:.1%}, "
            f"expected={expected_mechanism}, observed={dict(reason_counts)}"
        )

    fig, ax = plt.subplots(figsize=(8.8, 4.6))
    ax.bar(
        [row["scenario"] for row in rows],
        [row["rejection_rate"] * 100 for row in rows],
        color=[SSI_SERIES[idx % len(SSI_SERIES)] for idx in range(len(rows))],
        edgecolor="white",
        linewidth=0.8,
    )
    ax.set_ylim(0, 105)
    ax.set_ylabel("Rejection Rate (%)")
    panel_title(ax, "A", "Replay Rejection Rate by Scenario")
    ax.tick_params(axis="x", rotation=20)
    style_axes(ax, grid_axis="y")
    finalize_figure(fig, "s2_replay_rejection", "S2  Replay Resistance")

    payload = {
        "metadata": {
            "proofs_evaluated": trials,
            "notes": [
                "Replay scenarios are verifier-side evaluations of already accepted proofs.",
                "The four scenarios are aligned with the protocol mechanisms: exact replay, same (order,event) with new session, different order/event reuse, and stale proof.",
                "event_accepted corresponds to the verifier-side E_accepted registry keyed by (order_id, event).",
            ],
        },
        "rows": rows,
    }
    save_json("s2_replay_summary.json", payload)
    save_csv(
        "s2_replay_summary.csv",
        ["scenario", "expected_mechanism", "trials", "rejection_rate", "observed_mechanisms"],
        [
            {
                "scenario": row["scenario"],
                "expected_mechanism": row["expected_mechanism"],
                "trials": row["trials"],
                "rejection_rate": round(row["rejection_rate"], 6),
                "observed_mechanisms": json.dumps(row["observed_mechanisms"], sort_keys=True),
            }
            for row in rows
        ],
    )
    return payload


