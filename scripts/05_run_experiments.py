def percentile(values: Sequence[float], pct: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    idx = min(len(ordered) - 1, max(0, int(math.ceil((pct / 100.0) * len(ordered))) - 1))
    return ordered[idx]


def downsample_evenly(items: Sequence[WitnessNode], n: int) -> list[WitnessNode]:
    if n >= len(items):
        return list(items)
    if n <= 0:
        return []
    step = len(items) / n
    selected = []
    used = set()
    for idx in range(n):
        pos = min(len(items) - 1, int(idx * step))
        while pos in used and pos + 1 < len(items):
            pos += 1
        used.add(pos)
        selected.append(items[pos])
    return selected


