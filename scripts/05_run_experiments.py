def run_full_protocol(
    event: dict,
    witness_index: WitnessSpatialIndex,
    params: ProtocolParams,
    base_seed: int,
    tag: str,
    idx: int,
) -> dict:
    context = build_context(event, tag, idx)
    local_witnesses = witness_index.query(event["lat"], event["lon"], params.d_ble + 5.0)

    stable_seed(base_seed, tag, "proof", idx)
    proof_result = generate_proof(
        prover_id=event["order_id"],
        actual_lat=event["lat"],
        actual_lon=event["lon"],
        claim_lat=event["lat"],
        claim_lon=event["lon"],
        timestamp=event["time"],
        ctx=context,
        witnesses=local_witnesses,
        params=params,
        candidate_mode="actual",
    )

    if not proof_result.success:
        return {
            "accepted": False,
            "stage": "witness",
            "reason": first_reason(proof_result.rejection_reasons),
            "proof_result": proof_result,
            "context": context,
        }

    accepted, verify_reason = verify_proof(
        proof_result.proof,
        event["lat"],
        event["lon"],
        event["time"] - 1.0,
        event["time"] + 1.0,
        params,
        set(),
        expected_ctx=context,
    )
    return {
        "accepted": accepted,
        "stage": "accept" if accepted else "verifier",
        "reason": verify_reason,
        "proof_result": proof_result,
        "context": context,
    }


def collect_valid_proofs(
    events: Sequence[dict],
    witnesses: Sequence[WitnessNode],
    params: ProtocolParams,
    base_seed: int,
    limit: int,
    tag: str,
) -> list[dict]:
    witness_index = WitnessSpatialIndex(witnesses)
    accepted = []
    for idx, event in enumerate(events):
        outcome = run_full_protocol(event, witness_index, params, base_seed, tag, idx)
        if outcome["accepted"]:
            accepted.append(
                {
                    "event": event,
                    "proof": outcome["proof_result"].proof,
                    "context": outcome["context"],
                }
            )
            if len(accepted) >= limit:
                break
    return accepted


def evaluate_event_set(
    events: Sequence[dict],
    witnesses: Sequence[WitnessNode],
    params: ProtocolParams,
    base_seed: int,
    tag: str,
) -> dict:
    witness_index = WitnessSpatialIndex(witnesses)
    total = 0
    accepted = 0
    stage_counts = Counter()
    reason_counts = Counter()
    per_event_total = Counter()
    per_event_accept = Counter()

    for idx, event in enumerate(events):
        outcome = run_full_protocol(event, witness_index, params, base_seed, tag, idx)
        total += 1
        per_event_total[event["event"]] += 1
        if outcome["accepted"]:
            accepted += 1
            per_event_accept[event["event"]] += 1
        else:
            stage_counts[outcome["stage"]] += 1
            reason_counts[f"{outcome['stage']}:{outcome['reason']}"] += 1

    per_event_psr = {
        name: (
            per_event_accept[name] / per_event_total[name]
            if per_event_total[name] > 0
            else 0.0
        )
        for name in EVENT_ORDER
    }
    return {
        "accepted_events": accepted,
        "total_events": total,
        "overall_psr": accepted / total if total else 0.0,
        "per_event_psr": per_event_psr,
        "rejection_stage_counts": dict(stage_counts),
        "rejection_reason_counts": dict(reason_counts),
    }


def choose_recommended_deployment(rows: Sequence[dict]) -> dict:
    eligible = [row for row in rows if row["overall_psr"] >= 0.95]
    if eligible:
        eligible.sort(key=lambda row: (row["witness_count"], -row["overall_psr"], row["strategy"]))
        return {
            "mode": "psr_95",
            "row": eligible[0],
        }

    fallback = sorted(
        rows,
        key=lambda row: (-row["overall_psr"], row["witness_count"], row["strategy"]),
    )[0]
    return {
        "mode": "best_available",
        "row": fallback,
    }


def gps_only_verify(
    claim_lat: float,
    claim_lon: float,
    claim_time: float,
    expected_lat: float,
    expected_lon: float,
    expected_time_min: float,
    expected_time_max: float,
    params: ProtocolParams,
) -> tuple[bool, str]:
    if not (expected_time_min <= claim_time <= expected_time_max):
        return False, "temporal"
    if haversine(claim_lat, claim_lon, expected_lat, expected_lon) > params.r:
        return False, "spatial"
    return True, "accept"


def recommend_dt_range(rows: Sequence[dict]) -> dict:
    eligible = [
        row
        for row in rows
        if row["lar"] >= 0.95 and row["arr_mean"] >= 0.80
    ]
    if eligible:
        return {
            "mode": "constraint_based",
            "dt_min_ms": min(row["dt_ms"] for row in eligible),
            "dt_max_ms": max(row["dt_ms"] for row in eligible),
        }

    best = max(rows, key=lambda row: row["lar"] + row["arr_mean"] - 1.0)
    return {
        "mode": "best_tradeoff",
        "dt_min_ms": best["dt_ms"],
        "dt_max_ms": best["dt_ms"],
    }


def recommend_batch_range(rows: Sequence[dict]) -> dict:
    delay_capped = [row for row in rows if row["avg_anchor_delay_s"] <= 900]
    if delay_capped:
        min_delay_capped_gas = min(row["gas_per_proof"] for row in delay_capped)
        near_optimal = [
            row
            for row in delay_capped
            if row["gas_per_proof"] <= 2.05 * min_delay_capped_gas
        ]
        mins = [row["batch_minutes"] for row in near_optimal]
        return {
            "mode": "latency_capped",
            "batch_min_minutes": min(mins),
            "batch_max_minutes": max(mins),
        }

    best = min(rows, key=lambda row: row["gas_per_proof"] * (1 + row["avg_anchor_delay_s"] / 900))
    return {
        "mode": "best_tradeoff",
        "batch_min_minutes": best["batch_minutes"],
        "batch_max_minutes": best["batch_minutes"],
    }


