def collect_accepted_proof_hashes_for_deployment(
    events: Sequence[dict],
    witnesses: Sequence[WitnessNode],
    params: ProtocolParams,
    args: argparse.Namespace,
    limit: int,
) -> dict:
    accepted_records = collect_valid_proofs(
        events,
        witnesses,
        params,
        args.seed,
        limit=limit,
        tag="f3_pool",
    )
    proof_hashes = [proof_hash(item["proof"]) for item in accepted_records]
    return {
        "proof_hashes": proof_hashes,
        "accepted_records": accepted_records,
    }


