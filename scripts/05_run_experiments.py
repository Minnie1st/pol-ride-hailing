def smooth_curve(x_values: Sequence[float], y_values: Sequence[float], samples_per_segment: int = 40) -> tuple[np.ndarray, np.ndarray]:
    x = np.asarray(x_values, dtype=float)
    y = np.asarray(y_values, dtype=float)
    if len(x) < 3 or len(np.unique(x)) < 3:
        return x, y
    dense_x = np.linspace(x.min(), x.max(), max(len(x) * samples_per_segment, len(x)))
    dense_y = PchipInterpolator(x, y)(dense_x)
    return dense_x, np.clip(dense_y, 0.0, 100.0)


