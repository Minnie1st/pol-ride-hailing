def run_simple_pol(
    event: dict,
    witness_index: WitnessSpatialIndex,
    params: ProtocolParams,
    base_seed: int,
    tag: str,
    idx: int,
) -> dict:
    context = build_context(event, tag, idx)
    local_witnesses = witness_index.query(event["lat"], event["lon"], params.d_ble + 5.0)

    stable_seed(base_seed, tag, "proof", idx)
    proof_result = generate_proof(
        prover_id=event["order_id"],
        actual_lat=event["lat"],
        actual_lon=event["lon"],
        claim_lat=event["lat"],
        claim_lon=event["lon"],
        timestamp=event["time"],
        ctx=context,
        witnesses=local_witnesses,
        params=params,
        candidate_mode="actual",
    )

    if not proof_result.success:
        return {
            "accepted": False,
            "stage": "witness",
            "reason": first_reason(proof_result.rejection_reasons),
            "proof_result": proof_result,
            "context": context,
        }

    accepted, verify_reason = verify_proof(
        proof_result.proof,
        event["lat"],
        event["lon"],
        event["time"] - 1.0,
        event["time"] + 1.0,
        params,
        set(),
        expected_ctx=context,
    )
    return {
        "accepted": accepted,
        "stage": "accept" if accepted else "verifier",
        "reason": verify_reason,
        "proof_result": proof_result,
        "context": context,
    }


