class WitnessSpatialIndex:
    def __init__(self, witnesses: Sequence[WitnessNode], cell_lat: float = 0.001, cell_lon: float = 0.0015):
        self.witnesses = list(witnesses)
        self.cell_lat = cell_lat
        self.cell_lon = cell_lon
        self.grid: dict[tuple[int, int], list[WitnessNode]] = defaultdict(list)
        for witness in self.witnesses:
            self.grid[self._key(witness.lat, witness.lon)].append(witness)

    def _key(self, lat: float, lon: float) -> tuple[int, int]:
        return int(math.floor(lat / self.cell_lat)), int(math.floor(lon / self.cell_lon))

    def query(self, lat: float, lon: float, radius_m: float) -> list[WitnessNode]:
        lat_delta = radius_m / 111_320
        lon_scale = max(1e-9, math.cos(math.radians(lat)))
        lon_delta = radius_m / (111_320 * lon_scale)
        lat_min = lat - lat_delta
        lat_max = lat + lat_delta
        lon_min = lon - lon_delta
        lon_max = lon + lon_delta

        key_min = self._key(lat_min, lon_min)
        key_max = self._key(lat_max, lon_max)

        candidates: list[WitnessNode] = []
        for row in range(key_min[0], key_max[0] + 1):
            for col in range(key_min[1], key_max[1] + 1):
                candidates.extend(self.grid.get((row, col), []))

        filtered = [
            witness
            for witness in candidates
            if haversine(lat, lon, witness.lat, witness.lon) <= radius_m
        ]
        filtered.sort(key=lambda witness: haversine(lat, lon, witness.lat, witness.lon))
        return filtered


def build_random_order(all_witnesses: Sequence[WitnessNode], seed: int) -> list[WitnessNode]:
    ordered = list(sorted(all_witnesses, key=lambda witness: witness.id))
    rng = random.Random(seed)
    rng.shuffle(ordered)
    return ordered


def build_grid_order(all_witnesses: Sequence[WitnessNode], cell_lat: float = 0.001, cell_lon: float = 0.0015) -> list[WitnessNode]:
    buckets: dict[tuple[int, int], list[WitnessNode]] = defaultdict(list)
    for witness in sorted(all_witnesses, key=lambda item: (item.lat, item.lon, item.id)):
        key = int(math.floor(witness.lat / cell_lat)), int(math.floor(witness.lon / cell_lon))
        buckets[key].append(witness)

    keys = sorted(buckets)
    order: list[WitnessNode] = []
    positions = {key: 0 for key in keys}
    while True:
        progressed = False
        for key in keys:
            idx = positions[key]
            bucket = buckets[key]
            if idx < len(bucket):
                order.append(bucket[idx])
                positions[key] += 1
                progressed = True
        if not progressed:
            break
    return order


def build_hotspot_order(all_witnesses: Sequence[WitnessNode], events: Sequence[dict], cell_lat: float = 0.001, cell_lon: float = 0.0015) -> list[WitnessNode]:
    event_counts: Counter[tuple[int, int]] = Counter()
    for event in events:
        key = int(math.floor(event["lat"] / cell_lat)), int(math.floor(event["lon"] / cell_lon))
        event_counts[key] += 1

    scored = []
    for witness in all_witnesses:
        w_key = int(math.floor(witness.lat / cell_lat)), int(math.floor(witness.lon / cell_lon))
        score = 0
        for d_lat in (-1, 0, 1):
            for d_lon in (-1, 0, 1):
                score += event_counts.get((w_key[0] + d_lat, w_key[1] + d_lon), 0)
        scored.append((score, witness))

    scored.sort(key=lambda item: (-item[0], item[1].lat, item[1].lon, item[1].id))
    return [witness for _, witness in scored]


