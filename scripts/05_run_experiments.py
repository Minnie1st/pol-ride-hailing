def stable_seed(base_seed: int, *parts: Any) -> None:
    digest = hashlib.sha256(
        "|".join([str(base_seed), *[str(part) for part in parts]]).encode("utf-8")
    ).hexdigest()
    random.seed(int(digest[:16], 16))


def offset_point(lat: float, lon: float, distance_m: float, bearing_rad: float) -> tuple[float, float]:
    radius = 6_371_000
    phi1 = math.radians(lat)
    lam1 = math.radians(lon)
    ang = distance_m / radius

    phi2 = math.asin(
        math.sin(phi1) * math.cos(ang)
        + math.cos(phi1) * math.sin(ang) * math.cos(bearing_rad)
    )
    lam2 = lam1 + math.atan2(
        math.sin(bearing_rad) * math.sin(ang) * math.cos(phi1),
        math.cos(ang) - math.sin(phi1) * math.sin(phi2),
    )
    return math.degrees(phi2), math.degrees(lam2)


