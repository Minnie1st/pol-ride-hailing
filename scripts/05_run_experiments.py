def main() -> None:
    args = parse_args()
    experiments = selected_experiments(args)
    ensure_results_dir()

    print("Loading events, summaries, and witness candidates...")
    main_events = load_events("main")
    main_summary = load_summary("main")
    all_witnesses = load_witnesses()
    print(
        f"Loaded {len(main_events)} main events and {len(all_witnesses)} witness candidates "
        f"from {RESULTS_DIR}"
    )

    suite_summary: dict[str, Any] = {
        "seed": args.seed,
        "experiments": sorted(experiments),
    }

    strategy_orders = build_strategy_orders(all_witnesses, main_events, args.seed)

    security_proof_pool: list[dict] | None = None
    if experiments & {"s2", "s4"}:
        print("Collecting accepted proofs for replay/audit experiments...")
        security_proof_pool = collect_valid_proofs(
            main_events,
            all_witnesses,
            deployment_params(args),
            args.seed,
            limit=max(args.proof_pool_size, 128),
            tag="security_pool",
        )
        print(f"Collected {len(security_proof_pool)} accepted proofs for S2/S4 support")

    if "s1" in experiments:
        suite_summary["s1"] = experiment_s1_spoofing(all_witnesses, args)

    if "s2" in experiments:
        if not security_proof_pool:
            raise RuntimeError("S2 requested but no valid proof pool is available.")
        suite_summary["s2"] = experiment_s2_replay(security_proof_pool, args)

    if "s3" in experiments:
        suite_summary["s3"] = experiment_s3_relay(all_witnesses, args)

    if "s4" in experiments:
        if not security_proof_pool:
            raise RuntimeError("S4 requested but no valid proof pool is available.")
        suite_summary["s4"] = experiment_s4_audit(security_proof_pool, args)

    f1_result = None
    if experiments & {"f1", "f2", "f3", "s5"}:
        f1_result = experiment_f1(main_events, main_summary, strategy_orders, args)
        suite_summary["f1"] = f1_result

    if "s5" in experiments:
        if f1_result is None:
            raise RuntimeError("S5 requires F1 to establish the recommended deployment.")
        suite_summary["s5"] = experiment_s5_baselines(
            main_events,
            strategy_orders,
            f1_result["recommended_deployment"],
            args,
        )

    if "f2" in experiments:
        if f1_result is None:
            raise RuntimeError("F2 requires F1 to establish the recommended deployment.")
        suite_summary["f2"] = experiment_f2(
            strategy_orders,
            f1_result["recommended_deployment"],
            args,
        )

    if "f3" in experiments:
        if f1_result is None:
            raise RuntimeError("F3 requires F1 to establish the recommended deployment.")
        suite_summary["f3"] = experiment_f3(
            main_events,
            main_summary,
            strategy_orders,
            f1_result["recommended_deployment"],
            args,
        )

    summary_path = save_json("experiment_suite_summary.json", suite_summary)
    print("\n" + "=" * 72)
    print("Experiment Suite Completed")
    print("=" * 72)
    print(f"Saved suite summary to: {summary_path}")


if __name__ == "__main__":
    main()
