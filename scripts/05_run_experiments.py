def experiment_s4_audit(valid_proofs: Sequence[dict], args: argparse.Namespace) -> dict:
    print("\n" + "=" * 72)
    print("S4: On-chain Tamper Detection and Audit Closure")
    print("=" * 72)

    if len(valid_proofs) < 8:
        raise RuntimeError("S4 needs at least 8 accepted proofs to build a batch.")

    batch_size = min(128, len(valid_proofs))
    batch_records = list(valid_proofs[:batch_size])
    leaves = [proof_hash(item["proof"]) for item in batch_records]
    other_leaves = [hashlib.sha256(f"other:{idx}".encode("utf-8")).hexdigest() for idx in range(batch_size)]

    batch_registry: dict[int, str] = {}
    batch_id = 1001
    anchor_batch(batch_registry, batch_id, merkle_root(leaves))

    def mutated_leaf(index: int, field_name: str) -> str:
        proof = copy.deepcopy(batch_records[index]["proof"])
        if field_name == "claim_location":
            proof.claim.lat += 0.001
        elif field_name == "witness_timestamp":
            proof.attestations[0].timestamp += 120.0
        else:
            raise ValueError(f"Unsupported mutation field: {field_name}")
        return proof_hash(proof)

    scenario_rows = []
    scenario_names = [
        "valid_proof",
        "mutated_claim_location",
        "mutated_witness_timestamp",
        "missing_proof_record",
        "wrong_merkle_path",
        "wrong_root_mapping",
    ]

    for scenario_name in scenario_names:
        reason_counts = Counter()
        detected = 0
        accepted = 0
        trials = min(args.security_trials, batch_size)

        for idx in range(trials):
            if scenario_name == "valid_proof":
                audit = audit_batch_membership(batch_registry, batch_id, leaves, idx)
                if audit["accepted"]:
                    accepted += 1
                    reason_counts["accept"] += 1
                else:
                    detected += 1
                    reason_counts[audit["reason"]] += 1
                continue

            if scenario_name == "mutated_claim_location":
                audit = audit_batch_membership(
                    batch_registry,
                    batch_id,
                    leaves,
                    idx,
                    tampered_leaf=mutated_leaf(idx, "claim_location"),
                )
                if not audit["accepted"]:
                    detected += 1
                reason_counts[audit["reason"]] += 1
                continue

            if scenario_name == "mutated_witness_timestamp":
                audit = audit_batch_membership(
                    batch_registry,
                    batch_id,
                    leaves,
                    idx,
                    tampered_leaf=mutated_leaf(idx, "witness_timestamp"),
                )
                if not audit["accepted"]:
                    detected += 1
                reason_counts[audit["reason"]] += 1
                continue

            if scenario_name == "missing_proof_record":
                detected += 1
                reason_counts["proof_unavailable"] += 1
                continue

            if scenario_name == "wrong_merkle_path":
                path = merkle_path(leaves, idx)
                tampered_path = list(path)
                if tampered_path:
                    direction, sibling = tampered_path[0]
                    tampered_path[0] = (
                        direction,
                        hashlib.sha256((sibling + ":tamper").encode("utf-8")).hexdigest(),
                    )
                accepted_flag = verify_merkle_path(leaves[idx], tampered_path, batch_registry[batch_id])
                reason = "accept" if accepted_flag else "merkle_mismatch"
                if not accepted_flag:
                    detected += 1
                reason_counts[reason] += 1
                continue

            if scenario_name == "wrong_root_mapping":
                bad_registry = dict(batch_registry)
                bad_registry[batch_id] = merkle_root(other_leaves)
                audit = audit_batch_membership(bad_registry, batch_id, leaves, idx)
                if not audit["accepted"]:
                    detected += 1
                reason_counts[audit["reason"]] += 1

        row = {
            "scenario": scenario_name,
            "trials": trials,
            "accept_rate": accepted / trials if trials else 0.0,
            "detection_rate": detected / trials if trials else 0.0,
            "reason_counts": dict(reason_counts),
        }
        scenario_rows.append(row)
        metric = row["accept_rate"] if scenario_name == "valid_proof" else row["detection_rate"]
        label = "accept" if scenario_name == "valid_proof" else "detect"
        print(f"  {scenario_name:18s}: {label}={metric:.1%}, reasons={dict(reason_counts)}")

    complexity_rows = []
    for n in [8, 16, 32, 64, 128, 256, 512, 1024, 2048]:
        synthetic_leaves = [
            hashlib.sha256(f"batch:{n}:{idx}".encode("utf-8")).hexdigest()
            for idx in range(n)
        ]
        registry = {}
        anchor_batch(registry, n, merkle_root(synthetic_leaves))
        path_lengths = []
        elapsed_ms = []
        for idx in range(min(32, n)):
            audit = audit_batch_membership(registry, n, synthetic_leaves, idx)
            path_lengths.append(audit["path_length"])
            elapsed_ms.append(audit["elapsed_ms"])

        complexity_rows.append(
            {
                "batch_size": n,
                "avg_path_length": statistics.mean(path_lengths),
                "expected_log2": math.ceil(math.log2(n)),
                "avg_elapsed_ms": statistics.mean(elapsed_ms),
            }
        )

    fig, ax = plt.subplots(figsize=(6.2, 4.7))
    fig.patch.set_facecolor("white")
    ax.set_facecolor("white")

    x_values = [row["batch_size"] for row in complexity_rows]
    observed_values = [row["avg_path_length"] for row in complexity_rows]
    expected_values = [row["expected_log2"] for row in complexity_rows]
    ax.plot(
        x_values,
        observed_values,
        color=SSI["teal"],
        linestyle="-",
        linewidth=1.5,
        solid_capstyle="round",
        zorder=2,
    )
    ax.plot(
        x_values,
        observed_values,
        linestyle="None",
        marker="o",
        markersize=5.8,
        markerfacecolor="white",
        markeredgecolor=SSI["teal"],
        markeredgewidth=1.2,
        zorder=3,
    )
    ax.plot(
        x_values,
        expected_values,
        color=SSI["magenta"],
        linestyle="--",
        linewidth=1.5,
        zorder=2,
    )
    ax.plot(
        x_values,
        expected_values,
        linestyle="None",
        marker="s",
        markersize=5.8,
        markerfacecolor="white",
        markeredgecolor=SSI["magenta"],
        markeredgewidth=1.2,
        zorder=3,
    )
    ax.set_xscale("log", base=2)
    ax.set_xlabel("Batch Size", fontfamily="Times New Roman", fontsize=11.5)
    ax.set_ylabel("Merkle Path Length", fontfamily="Times New Roman", fontsize=11.5)
    ax.set_xticks(x_values)
    ax.get_xaxis().set_major_formatter(matplotlib.ticker.ScalarFormatter())
    style_axes(ax, grid_axis="both")
    ax.grid(True, axis="both", alpha=0.55, color=SSI["grid"], linestyle=(0, (4, 4)), linewidth=0.65)
    for side in ("top", "right", "left", "bottom"):
        ax.spines[side].set_visible(True)
        ax.spines[side].set_color("black")
        ax.spines[side].set_linewidth(1.0)
    ax.tick_params(axis="both", labelsize=10.2, length=0)
    for tick_label in ax.get_xticklabels() + ax.get_yticklabels():
        tick_label.set_fontfamily("Times New Roman")
    right_legend = ax.legend(
        handles=[
            Line2D(
                [0], [0],
                color=SSI["teal"], linestyle="-", linewidth=1.5,
                marker="o", markersize=5.8, markerfacecolor="white",
                markeredgecolor=SSI["teal"], markeredgewidth=1.2,
                label="Observed path length",
            ),
            Line2D(
                [0], [0],
                color=SSI["magenta"], linestyle="--", linewidth=1.5,
                marker="s", markersize=5.8, markerfacecolor="white",
                markeredgecolor=SSI["magenta"], markeredgewidth=1.2,
                label=r"$\lceil \log_2 n \rceil$",
            ),
        ],
        loc="upper left",
        frameon=True,
        facecolor="white",
        edgecolor=SSI["grid"],
        framealpha=0.96,
        fontsize=9.1,
    )
    if right_legend is not None:
        right_legend.get_frame().set_linewidth(0.8)
        for text in right_legend.get_texts():
            text.set_fontfamily("Times New Roman")

    finalize_figure(fig, "s4_audit_closure", title=None)

    payload = {
        "metadata": {
            "batch_id": batch_id,
            "anchoring_model": "anchorBatch(bytes32 merkleRoot, uint256 batchId)",
            "notes": [
                "All audit scenarios retrieve the Merkle root through batch_id from the anchoring registry.",
                "Proof-content tampering is modeled by mutating the proof object and recomputing the corresponding leaf commitment.",
                "The missing-proof scenario models audit failure when the platform cannot return the off-chain proof record.",
                "Complexity is validated via Merkle path length growth with batch size.",
                "In the left panel, the valid-proof bar reports acceptance rate, whereas the other five bars report detection rate.",
            ],
        },
        "scenario_rows": scenario_rows,
        "complexity_rows": complexity_rows,
    }
    save_json("s4_audit_closure.json", payload)
    save_csv(
        "s4_audit_scenarios.csv",
        ["scenario", "trials", "accept_rate", "detection_rate", "reason_counts"],
        [
            {
                "scenario": row["scenario"],
                "trials": row["trials"],
                "accept_rate": round(row["accept_rate"], 6),
                "detection_rate": round(row["detection_rate"], 6),
                "reason_counts": json.dumps(row["reason_counts"], sort_keys=True),
            }
            for row in scenario_rows
        ],
    )
    save_csv(
        "s4_audit_complexity.csv",
        ["batch_size", "avg_path_length", "expected_log2", "avg_elapsed_ms"],
        [
            {
                "batch_size": row["batch_size"],
                "avg_path_length": round(row["avg_path_length"], 6),
                "expected_log2": row["expected_log2"],
                "avg_elapsed_ms": round(row["avg_elapsed_ms"], 6),
            }
            for row in complexity_rows
        ],
    )
    return payload


def experiment_s5_baselines(
    main_events: Sequence[dict],
    strategy_orders: dict[str, list[WitnessNode]],
    recommended_deployment: dict,
    args: argparse.Namespace,
) -> dict:
    print("\n" + "=" * 72)
    print("S5: Comparison with GPS-only and Simple-PoL Baselines")
    print("=" * 72)

    deployment_row = recommended_deployment["row"]
    deployment = strategy_orders[deployment_row["strategy"]][: deployment_row["witness_count"]]
    witness_index = WitnessSpatialIndex(deployment)
    gps_params = deployment_params(args)
    simple_params = simple_pol_params(args)
    proposed_params = deployment_params(args)

    legitimate_trials = len(main_events)
    attack_trials = min(args.security_trials, len(main_events))

    scheme_rows: list[dict] = []
    attack_rows: list[dict] = []

    def append_scheme_row(
        scheme: str,
        attack_success: dict[str, float],
        lar: float,
    ) -> None:
        scheme_rows.append(
            {
                "scheme": scheme,
                "lar": lar,
                "spoofing_attack_success_rate": attack_success["spoofing"],
                "replay_attack_success_rate": attack_success["replay"],
                "collusion_attack_success_rate": attack_success["collusion"],
            }
        )
        for attack_name, value in attack_success.items():
            attack_rows.append(
                {
                    "scheme": scheme,
                    "attack": attack_name,
                    "attack_success_rate": value,
                }
            )

    gps_honest_accept = 0
    for event in main_events:
        accepted, _ = gps_only_verify(
            event["lat"],
            event["lon"],
            event["time"],
            event["lat"],
            event["lon"],
            event["time"] - 1.0,
            event["time"] + 1.0,
            gps_params,
        )
        if accepted:
            gps_honest_accept += 1
    gps_lar = gps_honest_accept / legitimate_trials if legitimate_trials else 0.0

    simple_honest_accept = 0
    for idx, event in enumerate(main_events):
        outcome = run_simple_pol(
            event,
            witness_index,
            simple_params,
            args.seed,
            "s5_simple_honest",
            idx,
        )
        if outcome["accepted"]:
            simple_honest_accept += 1
    simple_lar = simple_honest_accept / legitimate_trials if legitimate_trials else 0.0
    proposed_lar = deployment_row["overall_psr"]

    gps_spoof_accept = 0
    simple_spoof_accept = 0
    proposed_spoof_accept = 0
    for idx in range(attack_trials):
        event = main_events[idx]
        actual_lat, actual_lon = offset_point(
            event["lat"],
            event["lon"],
            5000.0,
            2 * math.pi * ((idx + 5) / (attack_trials + 7)),
        )
        accepted, _ = gps_only_verify(
            event["lat"],
            event["lon"],
            event["time"],
            event["lat"],
            event["lon"],
            event["time"] - 1.0,
            event["time"] + 1.0,
            gps_params,
        )
        gps_spoof_accept += int(accepted)

        for scheme_name, params, counter_name in [
            ("simple", simple_params, "simple"),
            ("proposed", proposed_params, "proposed"),
        ]:
            local_witnesses = witness_index.query(event["lat"], event["lon"], params.d_ble + 5.0)
            stable_seed(args.seed, "s5", scheme_name, "spoofing", idx)
            proof_result = generate_proof(
                prover_id=f"s5_spoof_{scheme_name}_{idx}",
                actual_lat=actual_lat,
                actual_lon=actual_lon,
                claim_lat=event["lat"],
                claim_lon=event["lon"],
                timestamp=event["time"],
                ctx=build_context(event, f"s5_{scheme_name}_spoof", idx),
                witnesses=local_witnesses,
                params=params,
                candidate_mode="claim",
            )
            accepted_flag = False
            if proof_result.success:
                accepted_flag, _ = verify_proof(
                    proof_result.proof,
                    event["lat"],
                    event["lon"],
                    event["time"] - 1.0,
                    event["time"] + 1.0,
                    params,
                    set(),
                    expected_ctx=build_context(event, f"s5_{scheme_name}_spoof", idx),
                )
            if accepted_flag and counter_name == "simple":
                simple_spoof_accept += 1
            if accepted_flag and counter_name == "proposed":
                proposed_spoof_accept += 1

    simple_pool = collect_valid_proofs(
        main_events,
        deployment,
        simple_params,
        args.seed,
        limit=max(attack_trials, 1),
        tag="s5_simple_pool",
    )
    proposed_pool = collect_valid_proofs(
        main_events,
        deployment,
        proposed_params,
        args.seed,
        limit=max(attack_trials, 1),
        tag="s5_proposed_pool",
    )
    replay_trials = min(attack_trials, len(simple_pool), len(proposed_pool))

    gps_replay_accept = replay_trials
    simple_replay_accept = 0
    proposed_replay_accept = 0

    for idx in range(replay_trials):
        simple_record = simple_pool[idx]
        simple_accepted, _ = verify_proof(
            simple_record["proof"],
            simple_record["event"]["lat"],
            simple_record["event"]["lon"],
            simple_record["event"]["time"] - 1.0,
            simple_record["event"]["time"] + 1.0,
            simple_params,
            set(),
            expected_ctx=simple_record["context"],
        )
        if simple_accepted:
            simple_replay_accept += 1

        proposed_record = proposed_pool[idx]
        c_used: set[str] = set()
        accepted_events: set[str] = set()
        verify_proof(
            proposed_record["proof"],
            proposed_record["event"]["lat"],
            proposed_record["event"]["lon"],
            proposed_record["event"]["time"] - 1.0,
            proposed_record["event"]["time"] + 1.0,
            proposed_params,
            c_used,
            expected_ctx=proposed_record["context"],
            accepted_events=accepted_events,
        )
        proposed_accepted, _ = verify_proof(
            proposed_record["proof"],
            proposed_record["event"]["lat"],
            proposed_record["event"]["lon"],
            proposed_record["event"]["time"] - 1.0,
            proposed_record["event"]["time"] + 1.0,
            proposed_params,
            c_used,
            expected_ctx=proposed_record["context"],
            accepted_events=accepted_events,
        )
        if proposed_accepted:
            proposed_replay_accept += 1

    gps_collusion_accept = attack_trials
    simple_collusion_accept = 0
    proposed_collusion_accept = 0
    for idx in range(attack_trials):
        event = main_events[idx]
        for scheme_name, params, counter_name in [
            ("simple", simple_params, "simple"),
            ("proposed", proposed_params, "proposed"),
        ]:
            local_witnesses = witness_index.query(event["lat"], event["lon"], params.d_ble + 5.0)
            stable_seed(args.seed, "s5", scheme_name, "collusion", idx)
            proof_result = generate_proof(
                prover_id=f"s5_collusion_{scheme_name}_{idx}",
                actual_lat=event["lat"],
                actual_lon=event["lon"],
                claim_lat=event["lat"],
                claim_lon=event["lon"],
                timestamp=event["time"],
                ctx=build_context(event, f"s5_{scheme_name}_collusion", idx),
                witnesses=local_witnesses,
                params=params,
                is_relay=True,
                relay_mode="ble_ble",
                candidate_mode="actual",
            )
            accepted_flag = False
            if proof_result.success:
                accepted_flag, _ = verify_proof(
                    proof_result.proof,
                    event["lat"],
                    event["lon"],
                    event["time"] - 1.0,
                    event["time"] + 1.0,
                    params,
                    set(),
                    expected_ctx=build_context(event, f"s5_{scheme_name}_collusion", idx),
                )
            if accepted_flag and counter_name == "simple":
                simple_collusion_accept += 1
            if accepted_flag and counter_name == "proposed":
                proposed_collusion_accept += 1

    append_scheme_row(
        "GPS-only",
        {
            "spoofing": gps_spoof_accept / attack_trials if attack_trials else 0.0,
            "replay": gps_replay_accept / replay_trials if replay_trials else 0.0,
            "collusion": gps_collusion_accept / attack_trials if attack_trials else 0.0,
        },
        gps_lar,
    )
    append_scheme_row(
        "Simple PoL",
        {
            "spoofing": simple_spoof_accept / attack_trials if attack_trials else 0.0,
            "replay": simple_replay_accept / replay_trials if replay_trials else 0.0,
            "collusion": simple_collusion_accept / attack_trials if attack_trials else 0.0,
        },
        simple_lar,
    )
    append_scheme_row(
        "Proposed",
        {
            "spoofing": proposed_spoof_accept / attack_trials if attack_trials else 0.0,
            "replay": proposed_replay_accept / replay_trials if replay_trials else 0.0,
            "collusion": proposed_collusion_accept / attack_trials if attack_trials else 0.0,
        },
        proposed_lar,
    )

    for row in scheme_rows:
        print(
            f"  {row['scheme']:10s}: LAR={row['lar']:.1%}, "
            f"spoof={row['spoofing_attack_success_rate']:.1%}, "
            f"replay={row['replay_attack_success_rate']:.1%}, "
            f"collusion={row['collusion_attack_success_rate']:.1%}"
        )

    fig, axes = plt.subplots(1, 2, figsize=(11.6, 4.8))
    scheme_order = ["GPS-only", "Simple PoL", "Proposed"]
    scheme_colors = {
        "GPS-only": SSI["teal"],
        "Simple PoL": SSI["mint"],
        "Proposed": SSI["magenta"],
    }
    attack_names = ["spoofing", "replay", "collusion"]
    x_positions = np.arange(len(attack_names))
    width = 0.24

    for offset_idx, scheme in enumerate(scheme_order):
        row = next(item for item in scheme_rows if item["scheme"] == scheme)
        axes[0].bar(
            x_positions + (offset_idx - 1) * width,
            [
                row["spoofing_attack_success_rate"] * 100,
                row["replay_attack_success_rate"] * 100,
                row["collusion_attack_success_rate"] * 100,
            ],
            width=width,
            color=scheme_colors[scheme],
            edgecolor="white",
            linewidth=0.8,
            label=scheme,
        )
    axes[0].set_xticks(x_positions)
    axes[0].set_xticklabels(["GPS spoofing", "Replay", "P-P Collusion"], fontfamily="Times New Roman")
    axes[0].set_ylim(0, 105)
    axes[0].set_ylabel("Attack Success Rate (%)", fontfamily="Times New Roman", fontsize=11)
    panel_title(axes[0], "A", "Security Comparison")
    style_axes(axes[0], grid_axis="y")
    style_legend(axes[0])

    x_positions = np.arange(len(scheme_order))
    axes[1].bar(
        x_positions,
        [next(item for item in scheme_rows if item["scheme"] == scheme)["lar"] * 100 for scheme in scheme_order],
        color=[scheme_colors[scheme] for scheme in scheme_order],
        edgecolor="white",
        linewidth=0.8,
    )
    axes[1].set_xticks(x_positions)
    axes[1].set_xticklabels(scheme_order, fontfamily="Times New Roman")
    axes[1].set_ylim(0, 105)
    axes[1].set_ylabel("LAR (%)", fontfamily="Times New Roman", fontsize=11)
    panel_title(axes[1], "B", "Legitimate Acceptance Comparison")
    style_axes(axes[1], grid_axis="y")

    finalize_figure(fig, "s5_baseline_comparison", "S5  Baseline Comparison")

    payload = {
        "metadata": {
            "deployment_strategy": deployment_row["strategy_label"],
            "deployment_count": deployment_row["witness_count"],
            "attack_trials": attack_trials,
            "replay_trials": replay_trials,
            "legitimate_trials": legitimate_trials,
            "d_ble": args.d_ble,
            "d_th": args.d_th,
            "tau_rssi": args.tau_rssi,
            "delta_t_max_ms": args.delta_t_max_ms,
            "baselines": {
                "GPS-only": "Server-side geofence and time-window validation only; no witness attestations or replay-state tracking.",
                "Simple PoL": "Single-witness proximity proof with witness-side checks, but without replay-state enforcement or anchoring.",
                "Proposed": "Full protocol with N_w=4, replay-state enforcement, and anchoring support.",
            },
            "notes": [
                "Baseline comparison uses the F1-recommended deployment so that the schemes are compared under the same operational witness layout.",
                "Replay comparison uses exact same-proof resubmission as the representative anti-replay stress case.",
                "Collusion comparison models prover-prover collusion as BLE+BLE forwarding under the common delta_t_max threshold.",
                "LAR denotes Legitimate Acceptance Rate.",
            ],
        },
        "rows": scheme_rows,
        "attack_rows": attack_rows,
    }
    save_json("s5_baseline_comparison.json", payload)
    save_csv(
        "s5_baseline_comparison.csv",
        [
            "scheme",
            "lar",
            "spoofing_attack_success_rate",
            "replay_attack_success_rate",
            "collusion_attack_success_rate",
        ],
        [
            {
                "scheme": row["scheme"],
                "lar": round(row["lar"], 6),
                "spoofing_attack_success_rate": round(row["spoofing_attack_success_rate"], 6),
                "replay_attack_success_rate": round(row["replay_attack_success_rate"], 6),
                "collusion_attack_success_rate": round(row["collusion_attack_success_rate"], 6),
            }
            for row in scheme_rows
        ],
    )
    return payload


